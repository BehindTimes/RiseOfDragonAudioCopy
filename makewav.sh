echo "=== Normalizing SD4 filenames to uppercase ==="
for f in "$SD4_DIR"/*; do
    [ -e "$f" ] || continue
    dir="$(dirname "$f")"
    base="$(basename "$f")"
    upper_base="${base^^}"
    if [ "$base" != "$upper_base" ]; then
        mv "$f" "$dir/$upper_base"
    fi
done

mkdir -p "$WAV_DIR"
echo "=== Extracting SD4 files to WAV ==="
for f in "$SD4_DIR"/*.SD4; do
    [ -e "$f" ] || continue
    name=$(basename -- "$f")
    name="${name%.*}"
    wine "$BASE_DIR/SegaPCM.exe" --start=32 --rate=16276 --output="$WAV_DIR/${name}.wav" "$f"
done

